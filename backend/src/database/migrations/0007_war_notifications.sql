-- War notifications for the Discord bot: one row per thing to post, written by the
-- war history ingest in the same transaction as the event it comes from. The bot
-- polls undelivered rows and acks each once Discord accepted it. See
-- docs/docs/map/war-history.md#discord-notifications.

CREATE TABLE war_notifications (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    realm_id text COLLATE "C" NOT NULL,
    war_key text COLLATE "C" NOT NULL,
    event_id text COLLATE "C" NOT NULL,
    kind text COLLATE "C" NOT NULL,
    -- Everything the bot needs to render the post, with no further lookups.
    payload jsonb NOT NULL DEFAULT '{}'::jsonb,
    created_at timestamptz NOT NULL DEFAULT now(),
    -- Last time a poll handed the row out; offered again 10 minutes later until acked.
    dispatched_at timestamptz,
    acked_at timestamptz,
    CONSTRAINT war_notifications_kind_check CHECK (kind IN (
        'war_declared', 'ally_joined', 'battle_day_set', 'battle_scheduled',
        'battle_postponed', 'battle_result', 'war_ended', 'defender_dm'))
);

-- One row per (event, kind); a defender DM is one row per Discord user of that event.
CREATE UNIQUE INDEX war_notifications_event_kind_idx
    ON war_notifications (event_id, kind, (COALESCE(payload ->> 'discord_user_id', '')));

-- The bot's poll: undelivered rows, oldest first.
CREATE INDEX war_notifications_pending_idx ON war_notifications (id) WHERE acked_at IS NULL;

-- Private: who to tell on Discord (SimpleFactions' `notify`). Never published.
ALTER TABLE war_events ADD COLUMN notify jsonb;

