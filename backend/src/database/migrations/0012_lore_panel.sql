-- The lore panel (/lore): the lore team's characters, organisations, storylines,
-- events, locations, availability and the Discord notification outbox. Staff and
-- lore team members only; switched off in production by LORE_PANEL (src/lore/flag.py).
-- See docs/docs/lore/README.md.

-- The lore team. Website staff have access without a row; leads manage the team.
CREATE TABLE lore_members (
    user_id bigint PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
    is_lead boolean NOT NULL DEFAULT false,
    added_by bigint REFERENCES users(id) ON DELETE SET NULL,
    added_at timestamptz NOT NULL DEFAULT now()
);

-- Per-person settings. A staff member with a row is on the roster (assignable, notified).
CREATE TABLE lore_profiles (
    user_id bigint PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
    timezone text COLLATE "C" CHECK (timezone IS NULL OR length(timezone) <= 64),
    notify_mode text COLLATE "C" NOT NULL DEFAULT 'available'
        CHECK (notify_mode IN ('off', 'available', 'all')),
    updated_at timestamptz NOT NULL DEFAULT now()
);

-- Weekly default availability; weekday 0 is Monday.
CREATE TABLE lore_weekly_availability (
    user_id bigint NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    weekday smallint NOT NULL CHECK (weekday BETWEEN 0 AND 6),
    status text COLLATE "C" NOT NULL CHECK (status IN ('full', 'partial', 'none')),
    note text COLLATE "C" NOT NULL DEFAULT '' CHECK (length(note) <= 200),
    PRIMARY KEY (user_id, weekday)
);

-- A day that differs from the weekly default. No row: the weekly default applies.
CREATE TABLE lore_availability (
    user_id bigint NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    day date NOT NULL,
    status text COLLATE "C" NOT NULL CHECK (status IN ('full', 'partial', 'none')),
    note text COLLATE "C" NOT NULL DEFAULT '' CHECK (length(note) <= 200),
    PRIMARY KEY (user_id, day)
);

CREATE TABLE lore_characters (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name text COLLATE "C" NOT NULL CHECK (length(btrim(name)) BETWEEN 1 AND 120),
    status text COLLATE "C" NOT NULL DEFAULT 'active' CHECK (status IN ('active', 'inactive', 'missing', 'dead')),
    summary text COLLATE "C" NOT NULL DEFAULT '' CHECK (length(summary) <= 2000),
    notes text COLLATE "C" NOT NULL DEFAULT '' CHECK (length(notes) <= 20000),
    -- 8x8 face from an uploaded skin; otherwise the linked player's head is shown.
    face_png bytea,
    player_uuid text COLLATE "C",
    player_name text COLLATE "C",
    version integer NOT NULL DEFAULT 1,
    deleted_at timestamptz,
    created_by bigint REFERENCES users(id) ON DELETE SET NULL,
    updated_by bigint REFERENCES users(id) ON DELETE SET NULL,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE lore_organisations (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name text COLLATE "C" NOT NULL CHECK (length(btrim(name)) BETWEEN 1 AND 120),
    kind text COLLATE "C" NOT NULL DEFAULT '' CHECK (length(kind) <= 60),
    game_faction text COLLATE "C" NOT NULL DEFAULT '' CHECK (length(game_faction) <= 120),
    summary text COLLATE "C" NOT NULL DEFAULT '' CHECK (length(summary) <= 2000),
    notes text COLLATE "C" NOT NULL DEFAULT '' CHECK (length(notes) <= 20000),
    version integer NOT NULL DEFAULT 1,
    deleted_at timestamptz,
    created_by bigint REFERENCES users(id) ON DELETE SET NULL,
    updated_by bigint REFERENCES users(id) ON DELETE SET NULL,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE lore_character_affiliations (
    character_id bigint NOT NULL REFERENCES lore_characters(id) ON DELETE CASCADE,
    organisation_id bigint NOT NULL REFERENCES lore_organisations(id) ON DELETE CASCADE,
    role text COLLATE "C" NOT NULL DEFAULT '' CHECK (length(role) <= 80),
    PRIMARY KEY (character_id, organisation_id)
);
CREATE INDEX lore_character_affiliations_org_idx ON lore_character_affiliations (organisation_id);

-- One-sided: how the source sees the target. Each side may describe the other differently.
CREATE TABLE lore_relations (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_kind text COLLATE "C" NOT NULL CHECK (source_kind IN ('character', 'organisation')),
    source_id bigint NOT NULL,
    target_kind text COLLATE "C" NOT NULL CHECK (target_kind IN ('character', 'organisation')),
    target_id bigint NOT NULL,
    type text COLLATE "C" NOT NULL
        CHECK (type IN ('ally', 'friendly', 'neutral', 'unfriendly', 'hostile', 'rival', 'family')),
    note text COLLATE "C" NOT NULL DEFAULT '' CHECK (length(note) <= 500),
    CHECK (NOT (source_kind = target_kind AND source_id = target_id)),
    UNIQUE (source_kind, source_id, target_kind, target_id)
);
CREATE INDEX lore_relations_target_idx ON lore_relations (target_kind, target_id);

CREATE TABLE lore_storylines (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title text COLLATE "C" NOT NULL CHECK (length(btrim(title)) BETWEEN 1 AND 120),
    status text COLLATE "C" NOT NULL DEFAULT 'planning'
        CHECK (status IN ('planning', 'active', 'concluded', 'abandoned')),
    summary text COLLATE "C" NOT NULL DEFAULT '' CHECK (length(summary) <= 2000),
    notes text COLLATE "C" NOT NULL DEFAULT '' CHECK (length(notes) <= 20000),
    version integer NOT NULL DEFAULT 1,
    deleted_at timestamptz,
    created_by bigint REFERENCES users(id) ON DELETE SET NULL,
    updated_by bigint REFERENCES users(id) ON DELETE SET NULL,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now()
);

-- Who and where a storyline involves.
CREATE TABLE lore_storyline_members (
    storyline_id bigint NOT NULL REFERENCES lore_storylines(id) ON DELETE CASCADE,
    kind text COLLATE "C" NOT NULL CHECK (kind IN ('character', 'organisation', 'location')),
    ref_id bigint NOT NULL,
    PRIMARY KEY (storyline_id, kind, ref_id)
);
CREATE INDEX lore_storyline_members_ref_idx ON lore_storyline_members (kind, ref_id);

-- Block coordinates on the main map; y is optional (the /tp command then keeps the player's height).
CREATE TABLE lore_locations (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name text COLLATE "C" NOT NULL CHECK (length(btrim(name)) BETWEEN 1 AND 120),
    world text COLLATE "C" NOT NULL DEFAULT 'TFMC_Map' CHECK (length(world) BETWEEN 1 AND 64),
    x integer NOT NULL DEFAULT 0 CHECK (x BETWEEN -30000000 AND 30000000),
    y integer CHECK (y BETWEEN -2048 AND 2048),
    z integer NOT NULL DEFAULT 0 CHECK (z BETWEEN -30000000 AND 30000000),
    kind text COLLATE "C" NOT NULL DEFAULT 'other'
        CHECK (kind IN ('settlement', 'landmark', 'camp', 'ruin', 'event', 'other')),
    summary text COLLATE "C" NOT NULL DEFAULT '' CHECK (length(summary) <= 2000),
    notes text COLLATE "C" NOT NULL DEFAULT '' CHECK (length(notes) <= 20000),
    version integer NOT NULL DEFAULT 1,
    deleted_at timestamptz,
    created_by bigint REFERENCES users(id) ON DELETE SET NULL,
    updated_by bigint REFERENCES users(id) ON DELETE SET NULL,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now()
);

-- An event either has a day (scheduled) or says what it waits on.
CREATE TABLE lore_events (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title text COLLATE "C" NOT NULL CHECK (length(btrim(title)) BETWEEN 1 AND 120),
    status text COLLATE "C" NOT NULL DEFAULT 'idea'
        CHECK (status IN ('idea', 'waiting', 'scheduled', 'done', 'cancelled')),
    storyline_id bigint REFERENCES lore_storylines(id) ON DELETE SET NULL,
    storyline_position integer,
    scheduled_on date,
    -- Optional exact start; the day stays the source of truth for the calendar.
    starts_at timestamptz,
    waiting_on text COLLATE "C" NOT NULL DEFAULT '' CHECK (length(waiting_on) <= 300),
    location_id bigint REFERENCES lore_locations(id) ON DELETE SET NULL,
    summary text COLLATE "C" NOT NULL DEFAULT '' CHECK (length(summary) <= 2000),
    notes text COLLATE "C" NOT NULL DEFAULT '' CHECK (length(notes) <= 20000),
    outcome text COLLATE "C" NOT NULL DEFAULT '' CHECK (length(outcome) <= 20000),
    version integer NOT NULL DEFAULT 1,
    deleted_at timestamptz,
    created_by bigint REFERENCES users(id) ON DELETE SET NULL,
    updated_by bigint REFERENCES users(id) ON DELETE SET NULL,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT lore_events_scheduled_day CHECK (status <> 'scheduled' OR scheduled_on IS NOT NULL),
    CONSTRAINT lore_events_waiting_on CHECK (status <> 'waiting' OR length(btrim(waiting_on)) > 0)
);
CREATE INDEX lore_events_day_idx ON lore_events (scheduled_on) WHERE deleted_at IS NULL;
CREATE INDEX lore_events_storyline_idx ON lore_events (storyline_id, storyline_position);

CREATE TABLE lore_event_helpers (
    event_id bigint NOT NULL REFERENCES lore_events(id) ON DELETE CASCADE,
    user_id bigint NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    PRIMARY KEY (event_id, user_id)
);
CREATE INDEX lore_event_helpers_user_idx ON lore_event_helpers (user_id);

CREATE TABLE lore_event_characters (
    event_id bigint NOT NULL REFERENCES lore_events(id) ON DELETE CASCADE,
    character_id bigint NOT NULL REFERENCES lore_characters(id) ON DELETE CASCADE,
    PRIMARY KEY (event_id, character_id)
);
CREATE INDEX lore_event_characters_character_idx ON lore_event_characters (character_id);

-- [[kind:id|Name]] links in long text, rebuilt whenever the source is saved; read as backlinks.
CREATE TABLE lore_mentions (
    source_kind text COLLATE "C" NOT NULL,
    source_id bigint NOT NULL,
    target_kind text COLLATE "C" NOT NULL,
    target_id bigint NOT NULL,
    PRIMARY KEY (source_kind, source_id, target_kind, target_id)
);
CREATE INDEX lore_mentions_target_idx ON lore_mentions (target_kind, target_id);

-- Who changed what. `changes` maps a field to [old, new].
CREATE TABLE lore_history (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    entity_kind text COLLATE "C" NOT NULL,
    entity_id bigint NOT NULL,
    action text COLLATE "C" NOT NULL,
    actor_user_id bigint REFERENCES users(id) ON DELETE SET NULL,
    actor_name text COLLATE "C" NOT NULL DEFAULT '',
    at timestamptz NOT NULL DEFAULT now(),
    changes jsonb NOT NULL DEFAULT '{}'::jsonb
);
CREATE INDEX lore_history_entity_idx ON lore_history (entity_kind, entity_id, at DESC);
CREATE INDEX lore_history_at_idx ON lore_history (at DESC);

-- Discord DMs about lore events for the bot, written in the same transaction as the
-- change. Same poll/ack contract as war_notifications (0007).
CREATE TABLE lore_notifications (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kind text COLLATE "C" NOT NULL
        CHECK (kind IN ('event_scheduled', 'event_rescheduled', 'event_cancelled')),
    event_id bigint NOT NULL,
    discord_user_id text COLLATE "C" NOT NULL,
    event_day date NOT NULL,
    payload jsonb NOT NULL DEFAULT '{}'::jsonb,
    created_at timestamptz NOT NULL DEFAULT now(),
    dispatched_at timestamptz,
    acked_at timestamptz,
    UNIQUE (event_id, kind, discord_user_id, event_day)
);
CREATE INDEX lore_notifications_pending_idx ON lore_notifications (id) WHERE acked_at IS NULL;

CREATE TABLE lore_notification_outbox (
    id integer PRIMARY KEY CHECK (id = 1),
    outbox_id uuid NOT NULL DEFAULT gen_random_uuid()
);
