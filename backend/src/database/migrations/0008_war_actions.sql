-- War actions (contract addendum v1.3): votes and call to arms answers made on the
-- website or from a Discord DM. Each is queued here and applied by SimpleFactions,
-- which re-checks it with the in-game rules and reports the result. See
-- docs/docs/map/war-history.md#war-actions.

CREATE TABLE war_actions (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    realm_id text COLLATE "C" NOT NULL,
    war_key text COLLATE "C" NOT NULL,
    kind text COLLATE "C" NOT NULL,
    -- The Minecraft account the action is made for, lower case with dashes.
    account_uuid text COLLATE "C" NOT NULL,
    discord_user_id text COLLATE "C",
    source text COLLATE "C" NOT NULL,
    payload jsonb NOT NULL DEFAULT '{}'::jsonb,
    status text COLLATE "C" NOT NULL DEFAULT 'pending',
    -- A plain player-facing sentence for a refusal or an expiry.
    reason text COLLATE "C",
    -- Whether the same action may work on a later try (a battle being fought, a server failure, an expiry).
    retry boolean NOT NULL DEFAULT false,
    created_at timestamptz NOT NULL DEFAULT now(),
    -- Last time the plugin's poll handed the row out.
    delivered_at timestamptz,
    applied_at timestamptz,
    CONSTRAINT war_actions_kind_check CHECK (kind IN ('call_to_arms_answer', 'day_vote', 'hour_vote')),
    CONSTRAINT war_actions_source_check CHECK (source IN ('web', 'discord')),
    CONSTRAINT war_actions_status_check CHECK (status IN ('pending', 'applied', 'rejected', 'expired'))
);

-- The plugin's poll: pending rows of one realm, oldest first.
CREATE INDEX war_actions_pending_idx ON war_actions (realm_id, id) WHERE status = 'pending';

-- Expiring rows still pending ten minutes after creation.
CREATE INDEX war_actions_pending_age_idx ON war_actions (created_at) WHERE status = 'pending';

-- One account's latest action per war and kind (/me, and replacing a pending vote).
CREATE INDEX war_actions_account_idx ON war_actions (realm_id, war_key, account_uuid, kind, id DESC);

-- Private SimpleFactions data on events (`private`: the open vote, who to notify).
-- Never published. `wars.private` keeps the latest `voting` block of each war.
ALTER TABLE war_events ADD COLUMN private jsonb;
ALTER TABLE wars ADD COLUMN private jsonb;

-- The silent event types of v1.3: no timeline entry, no channel post.
ALTER TABLE war_events DROP CONSTRAINT war_events_type_check;
ALTER TABLE war_events ADD CONSTRAINT war_events_type_check CHECK (type IN (
    'war_declared', 'participant_joined', 'day_vote_closed', 'battle_scheduled',
    'battle_postponed', 'battle_resolved', 'war_ended', 'next_battle_day',
    'votes_changed', 'call_to_arms_sent', 'call_to_arms_closed'));

-- A call to arms DM to the called faction's leader.
ALTER TABLE war_notifications DROP CONSTRAINT war_notifications_kind_check;
ALTER TABLE war_notifications ADD CONSTRAINT war_notifications_kind_check CHECK (kind IN (
    'war_declared', 'ally_joined', 'battle_day_set', 'battle_scheduled',
    'battle_postponed', 'battle_result', 'war_ended', 'defender_dm', 'call_to_arms_dm'));
